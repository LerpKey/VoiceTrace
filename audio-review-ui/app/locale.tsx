export const localeResources: Record<Locale, Record<string, string>> = { en, "zh-CN": zhCN };

export function formatMessage(locale: Locale, key: string, values: MessageValues = {}) {
  const template = localeResources[locale][key] ?? localeResources.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}

export function useLocale() {
  const locale = useSyncExternalStore(subscribeToLocale, readStoredLocale, () => "en");

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const setLocale = useCallback((next: Locale) => {
    window.localStorage.setItem(STORAGE_KEY, next);
    window.dispatchEvent(new Event(LOCALE_EVENT));
  }, []);

  const t = useCallback(
    (key: string, values: MessageValues = {}) => formatMessage(locale, key, values),
    [locale],
  );

  return { locale, setLocale, t };
}

