export function localizeServerText(locale: Locale, value: string | null | undefined) {
  if (!value || locale === "en") return value ?? "";
  const partial = value.match(/^Text review complete: (\d+) windows kept the original recognition because of the cost cap$/);
  if (partial) return formatMessage(locale, "serverTextReviewPartial", { count: partial[1] });
  const fallback = value.match(/^Text review fallback: (.*)$/);
  if (fallback) return formatMessage(locale, "serverTextReviewFallback", { detail: fallback[1] });
  return value;
}

